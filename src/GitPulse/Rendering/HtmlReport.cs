using System.Globalization;

using System.Text;
using GitPulse.Models;
using Spectre.Console;
using Spectre.Console.Rendering;

namespace GitPulse.Rendering;

/// <summary>
/// Builds the <c>report --html</c> page: every view rendered at a fixed width into an off-screen
/// console, recorded with Spectre's <see cref="Recorder"/>, exported with <c>ExportHtml</c>, and
/// wrapped in a small standalone HTML page (no scripts, no external files).
/// </summary>
internal static class HtmlReport
{
    /// <summary>Reports always render at this width, whatever the terminal is.</summary>
    public const int Width = 120;

    public static string Build(RepoStats stats, int top, DateTimeOffset generatedAt)
    {
        var sections = new (string Title, IRenderable View)[]
        {
            ("Overview", OverviewRenderer.Render(stats, Width)),
            ("Activity", ActivityRenderer.Render(stats, Width)),
            ("Authors", AuthorsRenderer.Render(stats, top, Width)),
            ("Hotspots", HotspotsRenderer.Render(stats, top, Width)),
        };

        var title = $"GitPulse · {stats.Summary.Name}";
        var html = new StringBuilder();
        html.Append("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
        html.Append("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        html.Append(CultureInfo.InvariantCulture, $"<title>{Encode(title)}</title>\n");
        html.Append("<style>\n").Append(Css).Append("</style>\n</head>\n<body>\n<main>\n");
        html.Append(CultureInfo.InvariantCulture, $"<h1>{Encode(title)}</h1>\n");
        html.Append(CultureInfo.InvariantCulture,
            $"<p class=\"meta\">{Encode(stats.Summary.Filter.Describe())} · generated {Encode(generatedAt.ToString("yyyy-MM-dd HH:mm zzz", CultureInfo.InvariantCulture))}</p>\n");

        foreach (var (sectionTitle, view) in sections)
        {
            html.Append(CultureInfo.InvariantCulture, $"<section>\n<h2>{Encode(sectionTitle)}</h2>\n");
            html.Append(Record(view)).Append('\n');
            html.Append("</section>\n");
        }

        html.Append("<footer>Generated by GitPulse. Read-only analysis of a local Git repository.</footer>\n");
        html.Append("</main>\n</body>\n</html>\n");
        return html.ToString();
    }

    /// <summary>Renders into a private, colored, 120-column console and returns the recorded HTML.</summary>
    internal static string Record(IRenderable view)
    {
        var console = AnsiConsole.Create(new AnsiConsoleSettings
        {
            Ansi = AnsiSupport.Yes,
            ColorSystem = ColorSystemSupport.TrueColor,
            Interactive = InteractionSupport.No,
            Out = new AnsiConsoleOutput(TextWriter.Null),
            // Don't let the user's NO_COLOR / TERM settings change the report.
            EnvironmentVariables = new Dictionary<string, string>(),
        });
        console.Profile.Width = Width;
        console.Profile.Height = 60;
        console.Profile.Capabilities.Unicode = true;
        console.Profile.Capabilities.Ansi = true; // so color-only widgets (the heatmap Canvas) draw in color

        using var recorder = new Recorder(console);
        recorder.Write(view);

        // Not recorder.ExportHtml(): Spectre's HTML encoder writes text unescaped, so a repository
        // name, author or path like "<script>" would become live HTML. SafeHtmlEncoder escapes it.
        return recorder.Export(new SafeHtmlEncoder());
    }

    /// <summary>Escapes the five HTML-significant characters only; the page is UTF-8, so "·" stays "·".</summary>
    internal static string Encode(string text) => text
        .Replace("&", "&amp;", StringComparison.Ordinal)
        .Replace("<", "&lt;", StringComparison.Ordinal)
        .Replace(">", "&gt;", StringComparison.Ordinal)
        .Replace("\"", "&quot;", StringComparison.Ordinal)
        .Replace("'", "&#39;", StringComparison.Ordinal);

    /// <summary>
    /// Turns recorded segments into <c>&lt;pre&gt;</c> HTML with inline styles. Every piece of text is
    /// HTML-escaped. Consecutive segments with the same style share one span to keep the file small.
    /// </summary>
    private sealed class SafeHtmlEncoder : IAnsiConsoleEncoder
    {
        public string Encode(IAnsiConsole console, IEnumerable<IRenderable> renderable)
        {
            var html = new StringBuilder("<pre>");
            var text = new StringBuilder();
            string? css = null;

            void Flush()
            {
                if (text.Length == 0)
                {
                    return;
                }

                var encoded = HtmlReport.Encode(text.ToString());
                html.Append(string.IsNullOrEmpty(css) ? encoded : $"<span style=\"{css}\">{encoded}</span>");
                text.Clear();
            }

            foreach (var segment in renderable.SelectMany(r => r.GetSegments(console)))
            {
                if (segment.IsControlCode)
                {
                    continue;
                }

                if (segment.IsLineBreak)
                {
                    Flush();
                    html.Append('\n');
                    continue;
                }

                var segmentCss = Css(segment.Style);
                if (segmentCss != css)
                {
                    Flush();
                    css = segmentCss;
                }

                text.Append(segment.Text);
            }

            Flush();
            return html.Append("</pre>").ToString();
        }

        private static string Css(Style style)
        {
            var (foreground, background) = style.Decoration.HasFlag(Decoration.Invert)
                ? (style.Background, style.Foreground)
                : (style.Foreground, style.Background);

            var parts = new List<string>();
            if (foreground != Color.Default)
            {
                parts.Add("color: #" + foreground.ToHex());
            }

            if (background != Color.Default)
            {
                parts.Add("background-color: #" + background.ToHex());
            }

            if (style.Decoration.HasFlag(Decoration.Bold))
            {
                parts.Add("font-weight: bold");
            }

            if (style.Decoration.HasFlag(Decoration.Italic))
            {
                parts.Add("font-style: italic");
            }

            if (style.Decoration.HasFlag(Decoration.Underline))
            {
                parts.Add("text-decoration: underline");
            }

            if (style.Decoration.HasFlag(Decoration.Dim))
            {
                parts.Add("opacity: 0.7");
            }

            return string.Join("; ", parts);
        }
    }

    private const string Css = """
        :root { color-scheme: dark; }
        body { margin: 0; background: #0d1117; color: #c9d1d9;
               font: 15px/1.5 system-ui, -apple-system, "Segoe UI", sans-serif; }
        main { max-width: 1100px; margin: 0 auto; padding: 24px 16px 48px; }
        h1 { font-size: 26px; margin: 0 0 4px; color: #87afff; }
        h2 { font-size: 18px; margin: 32px 0 8px; color: #87afff; }
        .meta, footer { color: #8b949e; font-size: 13px; }
        footer { margin-top: 40px; }
        pre { background: #010409; border: 1px solid #30363d; border-radius: 6px;
              padding: 12px; overflow-x: auto; line-height: 1.15;
              font: 13px/1.15 ui-monospace, "Cascadia Mono", Consolas, "DejaVu Sans Mono", monospace; }
        """;
}
